#!/usr/bin/env python3
"""
Static audit of the C++ generated by hxcpp for the spine runtime and the Ceramic
spine layer: counts, per function, the constructs that cost a lot when executed every
frame (dynamic field access and calls, closures, dynamic casts, type checks).

Usage: audit_cpp.py <hxcpp output dir (out/clay/mac/cpp)> <output.md>
"""
import os
import re
import sys

PATTERNS = [
    ('__Field', r'->__Field\(', 'dynamic field access (allocates a closure when called)'),
    ('closure', r'HX_BEGIN_LOCAL_FUNC|_hx_Closure_', 'local function (allocated closure)'),
    ('pose cast', r'\(\s*::spine::(BonePose|SlotPose|IkConstraintPose|TransformConstraintPose|PathConstraintPose|PhysicsConstraintPose|SliderPose)\)\(', 'pose read through a generic field (checked cast)'),
    ('StaticCast', r'StaticCast<', 'cast from Dynamic'),
    ('isOfType', r'Std_obj::isOfType|_hx_isInstanceOf|::hx::TCast', 'runtime type check'),
    ('new Array', r'::Array_obj< [^>]+ >::__new\(|::Array_obj<[^>]+>::__new\(', 'array allocation'),
    ('dynamic call', r'::Dynamic\(\s*\w+\s*\)\(|->__run\(|->__Run\(', 'dynamic function call'),
]

# Functions executed every frame, by file (relative to src/)
HOT = {
    'spine/Skeleton.cpp': ['updateWorldTransform', 'update'],
    'spine/BonePose.cpp': ['updateWorldTransform', 'update', 'updateLocalTransform', 'validateLocalTransform', 'modifyWorld', 'modifyLocal'],
    'spine/Bone.cpp': [],
    'spine/IkConstraint.cpp': ['update', 'apply1', 'apply2'],
    'spine/TransformConstraint.cpp': ['update'],
    'spine/PathConstraint.cpp': ['update', 'computeWorldPositions', 'addBeforePosition', 'addAfterPosition', 'addCurvePosition'],
    'spine/PhysicsConstraint.cpp': ['update'],
    'spine/Slider.cpp': ['update'],
    'spine/animation/AnimationState.cpp': ['update', 'updateMixingFrom', 'apply', 'applyMixingFrom', 'applyAttachmentTimeline', 'applyRotateTimeline', 'queueEvents'],
    'spine/animation/CurveTimeline.cpp': ['getBezierValue', 'getCurveValue'],
    'spine/animation/CurveTimeline1.cpp': ['getCurveValue', 'getRelativeValue', 'getAbsoluteValue', 'getScaleValue'],
    'spine/animation/RotateTimeline.cpp': ['apply'],
    'spine/animation/TranslateTimeline.cpp': ['apply'],
    'spine/animation/ScaleTimeline.cpp': ['apply'],
    'spine/animation/RGBATimeline.cpp': ['apply'],
    'spine/animation/DeformTimeline.cpp': ['apply'],
    'spine/animation/AttachmentTimeline.cpp': ['apply'],
    'spine/animation/DrawOrderTimeline.cpp': ['apply'],
    'spine/animation/EventTimeline.cpp': ['apply'],
    'spine/animation/IkConstraintTimeline.cpp': ['apply'],
    'spine/animation/EventQueue.cpp': ['drain'],
    'spine/animation/Listeners.cpp': ['invoke'],
    'spine/attachments/VertexAttachment.cpp': ['computeWorldVertices'],
    'spine/attachments/RegionAttachment.cpp': ['computeWorldVertices', 'getOffsets'],
    'spine/Sequence.cpp': ['resolveIndex', 'getUVs'],
    'spine/SkeletonClipping.cpp': ['clipStart', 'clipEnd', 'clipTriangles', 'clip'],
    'spine/ArrayUtils.cpp': ['resize'],
    'ceramic/Spine.cpp': ['render', 'updateSkeleton', 'update', 'applyClippedGeometry'],
}


def functions(text):
    """Yields (name, body) for each method definition of a generated file: the body is
    the text up to the next method definition (generated functions end with an
    indented brace, followed by HX_DEFINE_DYNAMIC_FUNC lines)."""
    headers = list(re.finditer(r'^\S[^\n]*?_obj::(\w+)\(([^\n]*)\)\s*\{\n', text, re.M))
    for i, m in enumerate(headers):
        end = headers[i + 1].start() if i + 1 < len(headers) else len(text)
        body = text[m.end():end]
        cut = body.find('\nHX_DEFINE_DYNAMIC_FUNC')
        if cut != -1:
            body = body[:cut]
        yield m.group(1), body


def main():
    if len(sys.argv) != 3:
        print(__doc__.strip())
        sys.exit(2)
    root = os.path.join(sys.argv[1], 'src')
    lines = ['# hxcpp audit of per frame code', '',
             'Counts of costly constructs in functions executed every frame. Each occurrence costs',
             'once per execution: inside loops, once per bone, slot, timeline or vertex.', '',
             '| file | function | ' + ' | '.join(p[0] for p in PATTERNS) + ' |',
             '|---|---|' + '---|' * len(PATTERNS)]
    for path, names in HOT.items():
        full = os.path.join(root, path)
        if not os.path.exists(full):
            continue
        text = open(full).read()
        for name, body in functions(text):
            if names and name not in names:
                continue
            counts = [len(re.findall(p[1], body)) for p in PATTERNS]
            if sum(counts) == 0:
                continue
            lines.append('| %s | %s | %s |' % (path, name, ' | '.join(str(c) if c else '' for c in counts)))
    lines.append('')
    lines.append('Legend:')
    for p in PATTERNS:
        lines.append('- **%s**: %s' % (p[0], p[2]))
    open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
